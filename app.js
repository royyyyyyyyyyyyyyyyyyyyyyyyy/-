function firstCharHints(lines) {
  return lines
    .flatMap((line) => splitScriptureLines(line.replace(/^第 \d+ 章：/, "")))
    .slice(0, 12)
    .map((line) => line.replace(/[，。；：！？、\s]/g, "").slice(0, Math.min(3, Math.max(1, line.length))));
}

function clozeLines(coach) {
  const words = (coach.keywords || []).filter((word) => word.length <= 4).slice(0, 12);
  return coach.lines.map((line) => {
    let value = line;
    words.forEach((word) => {
      value = value.replaceAll(word, "＿".repeat(Math.max(2, word.length)));
    });
    return value.replace(/^第 \d+ 章：/, "");
  });
}

function relayQuestions(lines) {
  const clean = lines.flatMap((line) => splitScriptureLines(line.replace(/^第 \d+ 章：/, ""))).filter(Boolean);
  return clean.slice(0, Math.max(1, clean.length - 1)).map((line, index) => ({
    prompt: line,
    answer: clean[index + 1] || "接到本章結尾。"
  }));
}

