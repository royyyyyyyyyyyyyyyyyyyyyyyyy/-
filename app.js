async function updateCheck(task, value) {
  const before = dayComplete(player, selectedDay);
  player.checks[key(selectedDay, task)] = value;
  if (!value) delete player.checks[key(selectedDay, task)];
  render();
  const result = await api(`/api/players/${player.id}/check`, {
    method: "POST",
    body: JSON.stringify({ day: selectedDay, task, checked: value })
  });
  player = normalizePlayer(result.player);
  await loadTeam();
  const after = dayComplete(player, selectedDay);
  render();
  if (!before && after) celebrate();
}

async function completeCurrentStage(advance) {
  const steps = stageSteps(selectedDay);
  const task = `stage-${currentStage}`;
  const wasLastStage = currentStage >= steps.length - 1;
  const before = dayComplete(player, selectedDay);

  player.checks[key(selectedDay, task)] = true;
  if (advance) currentStage = wasLastStage ? 0 : currentStage + 1;
  render();

  const result = await api(`/api/players/${player.id}/check`, {
    method: "POST",
    body: JSON.stringify({ day: selectedDay, task, checked: true })
  });
  player = normalizePlayer(result.player);
  await loadTeam();
  const after = dayComplete(player, selectedDay);
  render();
  if ((!before && after) || (advance && wasLastStage)) celebrate();
}

async function setMastery(day, level) {
  const targetDay = clampDay(day);
  const rating = Math.max(1, Math.min(5, Number(level) || 1));
  const id = memoryDayKey(targetDay);
  const now = new Date().toISOString();
  player.mastery ||= {};
  player.weakReviews ||= {};
  player.mastery[id] = { level: rating, updatedAt: now };

  const existing = player.weakReviews[id];
  if (rating >= 4) {
    delete player.weakReviews[id];
  } else if (rating < 3 || existing) {
    const misses = rating < 3 ? (Number(existing?.misses) || 0) + 1 : (Number(existing?.misses) || 1);
    const nextDay = misses === 2 ? selectedDay + 3 : selectedDay + 1;
    player.weakReviews[id] = {
      course: activeCourseId,
      day: targetDay,
      misses,
      level: rating,
      nextDay: Math.min(plan.length, nextDay),
      dailyUntilDay: misses >= 3 ? Math.min(plan.length, selectedDay + 7) : 0,
      daily: misses >= 4,
      updatedAt: now
    };
  }

  render();
  const result = await api(`/api/players/${player.id}`, {
    method: "PATCH",
    body: JSON.stringify({ mastery: player.mastery, weakReviews: player.weakReviews })
  });
  player = normalizePlayer(result.player);
  await loadTeam();
  render();
}

