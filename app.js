function speakText(text, label = "播放中", options = {}) {
  if (!speechAvailable()) {
    setSpeechStatus("這個瀏覽器不支援文字轉語音");
    return;
  }

  window.speechSynthesis.cancel();
  activeSpeechParts = [];
  activeSpeechSequenceLabel = "";
  activeSpeechText = text;
  activeSpeechLabel = label;
  speechLoop = Boolean(options.loop);
  const utterance = new SpeechSynthesisUtterance(localText(text));
  const voice = preferredSpeechVoice();
  if (voice) utterance.voice = voice;
  utterance.lang = voice?.lang || speechLanguage();
  utterance.rate = speechRate;
  utterance.pitch = 1;
  utterance.onstart = () => setSpeechStatus(label);
  utterance.onend = () => {
    if (activeUtterance === utterance) activeUtterance = null;
    if (speechLoop && activeSpeechText === text) {
      setSpeechStatus("循環播放中");
      setTimeout(() => {
        if (speechLoop && activeSpeechText === text) speakText(text, label, { loop: true });
      }, 360);
      return;
    }
    setSpeechStatus("播放完成");
  };
  utterance.onerror = () => {
    if (activeUtterance === utterance) activeUtterance = null;
    setSpeechStatus("朗讀中斷");
  };
  activeUtterance = utterance;
  refreshSpeechControls();
  window.speechSynthesis.speak(utterance);
}

function speakSequence(parts, label = "連續播放", options = {}) {
  if (!speechAvailable()) {
    setSpeechStatus("這個瀏覽器不支援文字轉語音");
    return;
  }
  const cleanParts = parts.map((part) => String(part || "").trim()).filter(Boolean);
  if (!cleanParts.length) return;

  window.speechSynthesis.cancel();
  activeSpeechParts = cleanParts;
  activeSpeechSequenceLabel = label;
  activeSpeechText = cleanParts.join("\n");
  activeSpeechLabel = label;
  speechLoop = Boolean(options.loop);
  let index = 0;

  const playNext = () => {
    if (!activeSpeechParts.length) return;
    if (index >= activeSpeechParts.length) {
      if (speechLoop) {
        index = 0;
      } else {
        activeUtterance = null;
        setSpeechStatus("播放完成");
        return;
      }
    }

    const utterance = new SpeechSynthesisUtterance(localText(activeSpeechParts[index]));
    const voice = preferredSpeechVoice();
    if (voice) utterance.voice = voice;
    utterance.lang = voice?.lang || speechLanguage();
    utterance.rate = speechRate;
    utterance.pitch = 1;
    utterance.onstart = () => setSpeechStatus(`${label} ${index + 1}/${activeSpeechParts.length}`);
    utterance.onend = () => {
      if (activeUtterance !== utterance) return;
      index += 1;
      setTimeout(playNext, 180);
    };
    utterance.onerror = () => {
      if (activeUtterance === utterance) activeUtterance = null;
      setSpeechStatus("朗讀中斷");
    };
    activeUtterance = utterance;
    refreshSpeechControls();
    window.speechSynthesis.speak(utterance);
  };

  playNext();
}

