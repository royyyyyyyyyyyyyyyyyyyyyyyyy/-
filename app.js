function weakNotebookItems() {
  const items = new Map();
  Object.entries(player.mastery || {}).forEach(([id, value]) => {
    const match = id.match(/^(.+):d(\d+)$/);
    const level = Number(typeof value === "object" ? value.level : value) || 0;
    if (!match || match[1] !== activeCourseId || level < 1 || level >= 3) return;
    items.set(Number(match[2]), { day: Number(match[2]), level });
  });
  Object.values(player.weakReviews || {}).forEach((item) => {
    if (item.course !== activeCourseId) return;
    const level = Number(item.level) || masteryLevel(item.day);
    if (level >= 3) return;
    items.set(Number(item.day), {
      day: Number(item.day),
      level: level || 1,
      misses: Number(item.misses) || 1
    });
  });
  return [...items.values()]
    .filter((item) => item.day >= 1 && item.day <= plan.length)
    .sort((a, b) => a.day - b.day);
}

