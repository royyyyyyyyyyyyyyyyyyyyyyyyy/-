async function startRecording() {
  const status = $("recordStatus");
  const playback = $("audioPlayback");
  if (!status || !playback) return;
  if (mediaRecorder && mediaRecorder.state === "recording") {
    status.textContent = "正在錄音中。背完後按停止錄音。";
    return;
  }
  stopSpeech();
  recordFallbackActive = false;
  recordStartedAt = Date.now();
  playback.innerHTML = "";
  const canRecord = Boolean(navigator.mediaDevices?.getUserMedia) && typeof MediaRecorder !== "undefined";
  if (!canRecord) {
    recordFallbackActive = true;
    status.textContent = "錄音檢核開始。這個預覽環境無法存音檔，請照樣盲背，背完按停止錄音。";
    playback.innerHTML = `<div class="record-fallback">口說計時中：背完後按「停止錄音」，再播放自我檢查或請夥伴旁聽。</div>`;
    return;
  }
  status.textContent = "正在開啟麥克風，請允許錄音權限。";
  audioChunks = [];
  try {
    const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
    const mimeType = ["audio/webm;codecs=opus", "audio/webm", "audio/mp4"].find((type) => MediaRecorder.isTypeSupported?.(type));
    mediaRecorder = new MediaRecorder(stream, mimeType ? { mimeType } : undefined);
    mediaRecorder.ondataavailable = (event) => {
      if (event.data.size > 0) audioChunks.push(event.data);
    };
    mediaRecorder.onstop = () => {
      const type = mediaRecorder?.mimeType || mimeType || "audio/webm";
      const blob = new Blob(audioChunks, { type });
      if (audioUrl) URL.revokeObjectURL(audioUrl);
      audioUrl = URL.createObjectURL(blob);
      playback.innerHTML = `<audio controls src="${audioUrl}"></audio>`;
      status.textContent = audioChunks.length
        ? "錄音完成，請播放聽一次，再決定通過或重背。"
        : "已停止，但沒有收到音訊；請再錄一次。";
      stream.getTracks().forEach((track) => track.stop());
    };
    mediaRecorder.start();
    status.textContent = "錄音中。背完後按停止錄音。";
  } catch (error) {
    recordFallbackActive = true;
    recordStartedAt = Date.now();
    status.textContent = "錄音檢核開始。若瀏覽器未開麥克風，這次先用口說計時完成。";
    playback.innerHTML = `<div class="record-fallback">口說計時中：背完後按「停止錄音」。</div>`;
  }
}

function stopRecording() {
  const status = $("recordStatus");
  const playback = $("audioPlayback");
  if (recordFallbackActive) {
    const seconds = Math.max(1, Math.round((Date.now() - recordStartedAt) / 1000));
    recordFallbackActive = false;
    if (status) status.textContent = `口說完成，已練習 ${seconds} 秒。請確認沒有看原文，再按通過本關。`;
    if (playback) playback.innerHTML = `<div class="record-fallback is-done">本次口說練習 ${seconds} 秒。</div>`;
    return;
  }
  if (mediaRecorder && mediaRecorder.state !== "inactive") {
    mediaRecorder.stop();
  } else if (status) {
    status.textContent = "目前沒有正在錄音。";
  }
}

function startAmbient() {
  const canvas = $("ambientCanvas");
  const ctx = canvas.getContext("2d");
  const points = Array.from({ length: 44 }, () => ({
    x: Math.random(),
    y: Math.random(),
    r: 1 + Math.random() * 2.8,
    s: 0.0008 + Math.random() * 0.0018,
    c: Math.random() > 0.55 ? "36,119,99" : "214,155,45"
  }));

  function resize() {
    canvas.width = window.innerWidth * devicePixelRatio;
    canvas.height = window.innerHeight * devicePixelRatio;
  }

  function draw() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    for (const point of points) {
      point.y -= point.s;
      if (point.y < -0.02) {
        point.y = 1.02;
        point.x = Math.random();
      }
      const x = point.x * canvas.width;
      const y = point.y * canvas.height;
      const gradient = ctx.createRadialGradient(x, y, 0, x, y, point.r * 18);
      gradient.addColorStop(0, `rgba(${point.c},0.32)`);
      gradient.addColorStop(1, `rgba(${point.c},0)`);
      ctx.fillStyle = gradient;
      ctx.beginPath();
      ctx.arc(x, y, point.r * 18, 0, Math.PI * 2);
      ctx.fill();
    }
    requestAnimationFrame(draw);
  }

  resize();
  window.addEventListener("resize", resize);
  draw();
}

