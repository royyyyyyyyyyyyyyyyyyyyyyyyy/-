function reviewItems() {
  const offsets = [3, 2, 1];
  const weakItems = weakReviewItems();
  const weakDays = new Set(weakItems.map((item) => item.day));
  const spacedItems = offsets
    .map((offset) => ({ offset, day: selectedDay - offset }))
    .filter((item) => item.day >= 1 && item.day <= plan.length)
    .filter((item) => !weakDays.has(item.day))
    .map((item) => {
      const coach = coachFor(item.day);
      const relay = reviewRelayFor(item.day);
      return {
        ...item,
        title: chaptersByDay[item.day - 1],
        badge: "前面 3 章",
        firstLine: coach.lines[0] || "原文待補",
        relay,
        keywords: coach.keywords || [],
        rescueId: `reviewRescue-${item.day}-${item.offset}`
      };
    });
  return [...weakItems, ...spacedItems];
}

function reviewRelayFor(day) {
  const coach = coachFor(day);
  const lines = coach.lines.filter(Boolean);
  if (lines.length <= 1) {
    return {
      prompt: lines[0] || plan[day - 1]?.title || "章節待補",
      answer: lines[0] || "原文待補"
    };
  }
  const index = Math.min(lines.length - 2, Math.abs((selectedDay + day) % (lines.length - 1)));
  return {
    prompt: lines[index],
    answer: lines[index + 1]
  };
}

