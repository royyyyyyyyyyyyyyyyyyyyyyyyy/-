function normalizeForCompare(text) {
  return String(text || "").replace(/[^\u4e00-\u9fff]/g, "");
}

function compareWriting(userText, targetText) {
  const target = normalizeForCompare(targetText);
  const typed = normalizeForCompare(userText);
  const rows = target.length + 1;
  const cols = typed.length + 1;
  const dp = Array.from({ length: rows }, () => Array(cols).fill(0));

  for (let i = target.length - 1; i >= 0; i -= 1) {
    for (let j = typed.length - 1; j >= 0; j -= 1) {
      dp[i][j] = target[i] === typed[j]
        ? dp[i + 1][j + 1] + 1
        : Math.max(dp[i + 1][j], dp[i][j + 1]);
    }
  }

  let i = 0;
  let j = 0;
  let html = "";
  let ok = 0;
  let missing = 0;
  let extra = 0;

  while (i < target.length && j < typed.length) {
    if (target[i] === typed[j]) {
      html += `<span class="diff-ok">${escapeHtml(target[i])}</span>`;
      ok += 1;
      i += 1;
      j += 1;
    } else if (dp[i + 1][j] >= dp[i][j + 1]) {
      html += `<span class="diff-miss">${escapeHtml(target[i])}</span>`;
      missing += 1;
      i += 1;
    } else {
      html += `<span class="diff-extra">${escapeHtml(typed[j])}</span>`;
      extra += 1;
      j += 1;
    }
  }

  while (i < target.length) {
    html += `<span class="diff-miss">${escapeHtml(target[i])}</span>`;
    missing += 1;
    i += 1;
  }

  while (j < typed.length) {
    html += `<span class="diff-extra">${escapeHtml(typed[j])}</span>`;
    extra += 1;
    j += 1;
  }

  const accuracy = target.length ? Math.round((ok / target.length) * 100) : 0;
  return `
    <div class="review-item">
      <strong>比對結果：${accuracy}%</strong>
      <span>正確 ${ok} 字，漏字/錯位 ${missing} 字，多寫/順序錯 ${extra} 字。</span>
    </div>
    <button class="plain-button" data-action="toggle-compare-detail">看原文對照</button>
    <div class="reference-box" id="compareDetail">
      <p class="compare-note">綠色是對的；紅色是漏字/錯位；黃色是多寫或順序跑掉。</p>
      <div class="diff-line">${html}</div>
    </div>
    <div class="review-item">
      <strong>提醒</strong>
      <span>先看統計，想修錯時再展開對照，避免太快偷看原文。</span>
    </div>
  `;
}

