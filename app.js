function speechVoiceScore(voice, mode) {
  const name = `${voice.name || ""} ${voice.voiceURI || ""}`.toLowerCase();
  const lang = String(voice.lang || "").toLowerCase();
  let score = 0;
  const wantsFemale = mode === "female";
  const wantsMale = mode === "male";

  if (lang === speechLanguage().toLowerCase()) score += 12;
  if (lang.startsWith("zh")) score += 6;

  if (wantsFemale && /(female|woman|女|hanhan|hsiao|xiaoxiao|xiaoyi|xiaomeng|huihui|yaoyao|meijia)/i.test(name)) score += 10;
  if (wantsMale && /(male|man|男|yun|yunjian|yunxi|yunjhe|zhiwei|kangkang|zhi|liang)/i.test(name)) score += 10;

  return score;
}

function preferredSpeechVoice(mode = speechVoiceMode) {
  if (!speechAvailable()) return null;
  const voices = window.speechSynthesis.getVoices();
  const ranked = voices
    .map((voice) => ({ voice, score: speechVoiceScore(voice, mode) }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score);
  return ranked[0]?.voice
    || voices.find((voice) => voice.lang === speechLanguage())
    || voices.find((voice) => voice.lang?.startsWith("zh"))
    || null;
}

