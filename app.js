async function api(path, options = {}) {
  const method = (options.method || "GET").toUpperCase();
  const body = options.body ? JSON.parse(options.body) : {};
  const data = readStaticData();

  if (method === "GET" && path === "/api/team") {
    return data;
  }

  if (method === "POST" && path === "/api/players") {
    const name = String(body.name || "").trim().replace(/\s+/g, " ").slice(0, 24);
    const region = String(body.region || "").trim().replace(/\s+/g, " ").slice(0, 18);
    if (!name) throw new Error("請輸入暱稱。");
    let nextPlayer = data.players.find((item) =>
      item.name.toLowerCase() === name.toLowerCase()
      && String(item.region || "").toLowerCase() === region.toLowerCase()
    );
    if (!nextPlayer) {
      nextPlayer = {
        id: makeId(),
        name,
        region,
        createdAt: new Date().toISOString(),
        selectedDay: 1,
        selectedCourse: activeCourseId,
        checks: {},
        notes: {},
        mistakes: [],
        mastery: {},
        weakReviews: {},
        lastSeenAt: new Date().toISOString()
      };
      data.players.push(nextPlayer);
    } else {
      nextPlayer.region = region;
    }
    nextPlayer.lastSeenAt = new Date().toISOString();
    writeStaticData(data);
    return { player: normalizePlayer(nextPlayer) };
  }

  const playerMatch = path.match(/^\/api\/players\/([^/]+)(?:\/([^/]+))?(?:\/([^/]+))?$/);
  if (!playerMatch) throw new Error("找不到資料。");

  const [, playerId, action, detail] = playerMatch;
  const nextPlayer = data.players.find((item) => item.id === playerId);
  if (!nextPlayer) throw new Error("找不到這位玩家。");

  nextPlayer.checks ||= {};
  nextPlayer.notes ||= {};
  nextPlayer.mistakes ||= [];
  nextPlayer.mastery ||= {};
  nextPlayer.weakReviews ||= {};
  nextPlayer.lastSeenAt = new Date().toISOString();

  if (method === "PATCH" && !action) {
    if (Number.isFinite(Number(body.selectedDay))) nextPlayer.selectedDay = clampDay(body.selectedDay);
    if (body.selectedCourse && courseCatalog[body.selectedCourse]) nextPlayer.selectedCourse = body.selectedCourse;
    if (typeof body.region === "string") nextPlayer.region = body.region.trim().replace(/\s+/g, " ").slice(0, 18);
    if (body.checks && typeof body.checks === "object") nextPlayer.checks = body.checks;
    if (body.notes && typeof body.notes === "object") nextPlayer.notes = body.notes;
    if (Array.isArray(body.mistakes)) nextPlayer.mistakes = body.mistakes.slice(0, 200);
    if (body.mastery && typeof body.mastery === "object") nextPlayer.mastery = body.mastery;
    if (body.weakReviews && typeof body.weakReviews === "object") nextPlayer.weakReviews = body.weakReviews;
    writeStaticData(data);
    return { player: normalizePlayer(nextPlayer) };
  }

  if (method === "POST" && action === "check") {
    const checkKey = key(Number(body.day), String(body.task || ""));
    if (body.checked) nextPlayer.checks[checkKey] = true;
    else delete nextPlayer.checks[checkKey];
    writeStaticData(data);
    return { player: normalizePlayer(nextPlayer) };
  }

  if (method === "POST" && action === "note") {
    const day = clampDay(body.day);
    nextPlayer.notes[`d${day}`] = String(body.note || "").slice(0, 4000);
    writeStaticData(data);
    return { player: normalizePlayer(nextPlayer) };
  }

  if (method === "POST" && action === "mistakes") {
    const text = String(body.text || "").trim().slice(0, 300);
    if (!text) throw new Error("錯句不能是空的。");
    nextPlayer.mistakes.push({
      id: makeId(),
      day: clampDay(body.day),
      text,
      createdAt: new Date().toISOString()
    });
    nextPlayer.mistakes = nextPlayer.mistakes.slice(-200);
    writeStaticData(data);
    return { player: normalizePlayer(nextPlayer) };
  }

  if (method === "DELETE" && action === "mistakes" && detail) {
    nextPlayer.mistakes = nextPlayer.mistakes.filter((item) => item.id !== detail);
    writeStaticData(data);
    return { player: normalizePlayer(nextPlayer) };
  }

  throw new Error("找不到資料。");
}

