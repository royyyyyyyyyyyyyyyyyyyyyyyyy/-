function cleanDiamondLine(line) {
  return String(line || "")
    .replace(/[「」『』]/g, "")
    .replace(/[─—－]/g, "")
    .replace(/\s+/g, "")
    .trim();
}

function shouldHoldDiamondLine(line) {
  return line.length < 8
    || /(?:希有！|善哉！|唯然！|世尊！|須菩提！|佛言：)$/.test(line)
    || /云何應住？$/.test(line);
}

