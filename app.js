function escapeHtml(text) {
  return String(text)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function highlightKeywords(text, keywords) {
  let html = escapeHtml(text);
  keywords.forEach((keyword, index) => {
    const safe = escapeHtml(keyword);
    if (!safe) return;
    html = html.replaceAll(safe, `<mark class="kw-mark kw-${index % 6}">${safe}</mark>`);
  });
  return html;
}

