function toSimplified(text) {
  let value = String(text ?? "");
  simplifiedPhrases.forEach(([from, to]) => {
    value = value.replaceAll(from, to);
  });
  return Array.from(value).map((char) => simplifiedChars[char] || char).join("");
}

function localText(text) {
  if (currentLanguage !== "zh-Hans") return String(text ?? "");
  let value = String(text ?? "");
  regionalPhrasesHans.forEach(([from, to]) => {
    value = value.replaceAll(from, to);
  });
  return toSimplified(value);
}

function dataKeyForAttribute(attribute) {
  return `i18n${attribute.replace(/(^|-)([a-z])/g, (_, __, letter) => letter.toUpperCase())}`;
}

function applyLanguage(root = document.body) {
  if (!root) return;
  document.documentElement.lang = currentLanguage;
  document.title = localText(`${activeCourse().title}背誦教練`);

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (parent.closest("script, style, textarea, input, [data-no-translate]")) {
        return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const textNodes = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode);
  textNodes.forEach((node) => {
    if (!node.__hantText) node.__hantText = node.nodeValue;
    node.nodeValue = localText(node.__hantText);
  });

  document.querySelectorAll("[placeholder], [aria-label], [alt], [title]").forEach((element) => {
    ["placeholder", "aria-label", "alt", "title"].forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      const keyName = dataKeyForAttribute(attribute);
      if (!element.dataset[keyName]) element.dataset[keyName] = element.getAttribute(attribute) || "";
      element.setAttribute(attribute, localText(element.dataset[keyName]));
    });
  });

  document.querySelectorAll("[data-lang-toggle]").forEach((button) => {
    button.textContent = currentLanguage === "zh-Hans" ? "语文：简" : "語文：繁";
    button.setAttribute(
      "aria-label",
      currentLanguage === "zh-Hans" ? "切换繁体中文" : "切換簡體中文"
    );
  });
}

